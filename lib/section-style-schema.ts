  // 與標題底線都開了虛線點線，色條還是只有實心一種。而色條偏偏是三條裡最當裝飾用的
  // ——它本來就不隔開誰，畫在段落邊上就是雜誌引言框那個手勢，深淺那格特地開了「淡」
