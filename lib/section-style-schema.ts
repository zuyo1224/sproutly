  // 有孔隙的線才真的輕。粗細那格反方向也一樣卡：8px 的粗檔配上點線是一排圓珠、配上
  // 虛線是一節一節的短棒——手作感網站拿來鑲頁緣的那種裝飾邊，實心檔做不出來。
  // 三檔跟分隔線、底線的線型一字不差，同一段裡三條線才配得起來。色條本來就畫在
  // borderLeft / borderRight 上，換線型只是 border 字串裡 solid 換個字，不用像底線那樣
